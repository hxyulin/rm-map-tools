"""Qualify possible enclosed cavity shells without altering source CAD."""
import argparse,json,sys
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2];sys.path.insert(0,str(ROOT/'python'))
from cad_detail_passes import fill_enclosed_voids
from cad_wall_fill import shape_map
from mesh_parts import tessellate
from plan_cad_lods import digest
from validate_parts import read_part
from OCP.TopAbs import TopAbs_SOLID,TopAbs_SHELL,TopAbs_FACE
from OCP.XCAFDoc import XCAFDoc_DocumentTool,XCAFDoc_ShapeTool
from OCP.collections import Sequence_TDF_Label

def main():
    ap=argparse.ArgumentParser(description=__doc__);ap.add_argument('--out',type=Path,required=True);a=ap.parse_args();audit=json.loads((a.out/'audit.json').read_bytes());results=[]
    for c in audit['components']:
        folder=ROOT/'out/rmuc2027-equipment-pipeline'/c['id'];source=folder/'source.step'
        if digest(source)!=c['source_step_sha256']:raise ValueError('source changed')
        doc,reader,error=read_part(str(source))
        if error:raise ValueError(error)
        roots=Sequence_TDF_Label();XCAFDoc_DocumentTool.ShapeTool_s(doc.Main()).GetFreeShapes(roots);root=XCAFDoc_ShapeTool.GetShape_s(roots.Value(1));solids=shape_map(root,TopAbs_SOLID);shells=shape_map(root,TopAbs_SHELL);candidates=[i for i in range(1,solids.Extent()+1) if shape_map(solids.FindKey(i),TopAbs_SHELL).Extent()>1];r={'id':c['id'],'source_step_sha256':c['source_step_sha256'],'native_solids':solids.Extent(),'multi_shell_solids':len(candidates),'checks':[]}
        if candidates:
            records=[];p,t,m,palette=tessellate(doc,.4,.25,{},lambda i,f,n:records.append((f,n)));colours={};offset=0
            for face,count in records:
                keys={palette[int(k)] for k in m[offset:offset+count]};offset+=count
                if len(keys)!=1:raise ValueError('ambiguous source face colour')
                colours[shape_map(root,TopAbs_FACE).FindIndex(face)]=next(iter(keys))
            global_faces=shape_map(root,TopAbs_FACE)
            for i in candidates:
                solid=solids.FindKey(i);faces=shape_map(solid,TopAbs_FACE);local_colours=[colours[global_faces.FindIndex(faces.FindKey(j))] for j in range(1,faces.Extent()+1)]
                try:
                    result=fill_enclosed_voids(solid,local_colours);retained=shape_map(result.shape,TopAbs_FACE);removed=[];local_shells=shape_map(solid,TopAbs_SHELL)
                    for j in range(1,local_shells.Extent()+1):
                        local=shape_map(local_shells.FindKey(j),TopAbs_FACE)
                        if all(not retained.Contains(local.FindKey(k)) for k in range(1,local.Extent()+1)):removed.append(shells.FindIndex(local_shells.FindKey(j)))
                    # Current/trial source-shell identities survive only because
                    # candidates are sourced from this exact component STEP.
                    import numpy as np
                    current=np.load(folder/'lod.npz');coarse=np.load(a.out/c['id']/'native-angular-trial.npz');current_cost=int(np.isin(current['unit_ids'],removed).sum());coarse_cost=int(np.isin(coarse['unit_ids'],removed).sum());check={'native_solid_index':i,'accepted':True,'proof':result.proof,'removed_native_shell_indices':removed,'current_cavity_triangles':current_cost,'angular_trial_cavity_triangles':coarse_cost,'uses':c['uses']}
                except ValueError as error:check={'native_solid_index':i,'accepted':False,'reason':str(error)}
                r['checks'].append(check)
        results.append(r);print(c['id'],'solids',r['native_solids'],'multi-shell',len(candidates),'accepted',sum(x['accepted'] for x in r['checks']),flush=True)
    (a.out/'cavities.json').write_text(json.dumps({'components':results,'producer_sha256':digest(Path(__file__)),'scope':'Native finite-surface containment/distance and exact retained outer-face identity checks on derived working solids. Source, approved meshes and runtime unchanged; no mesh replacement generated by this audit.'},indent=2)+'\n')

if __name__=='__main__':main()
