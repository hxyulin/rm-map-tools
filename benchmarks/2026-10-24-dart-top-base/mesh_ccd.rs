//! Opt-in mesh CCD check; CAD fixture is supplied at runtime outside source.
use rm_sim_physics::{Caliber, Pose, Shot, TargetFrames, WorldPhysics, tick_ns};

fn number(tokens: &mut std::str::SplitWhitespace<'_>) -> f64 {
    tokens.next().unwrap().parse().unwrap()
}
fn vector(tokens: &mut std::str::SplitWhitespace<'_>) -> [f64; 3] {
    [number(tokens), number(tokens), number(tokens)]
}
fn dot(a: [f64; 3], b: [f64; 3]) -> f64 {
    a.into_iter().zip(b).map(|(x, y)| x * y).sum()
}

#[test]
#[ignore = "requires RM_DART_CCD_FIXTURE_TXT generated by rm-map-tools"]
fn profile_meshes_stop_projectiles() {
    let path = std::env::var("RM_DART_CCD_FIXTURE_TXT").unwrap();
    let text = std::fs::read_to_string(path).unwrap();
    let mut tokens = text.split_whitespace();
    assert_eq!(tokens.next(), Some("MESHES"));
    let count: usize = tokens.next().unwrap().parse().unwrap();
    let mut meshes = Vec::new();
    for _ in 0..count {
        assert_eq!(tokens.next(), Some("M"));
        let vertices: usize = tokens.next().unwrap().parse().unwrap();
        let triangles: usize = tokens.next().unwrap().parse().unwrap();
        let points: Vec<[f64; 3]> = (0..vertices).map(|_| vector(&mut tokens)).collect();
        let indices: Vec<[u32; 3]> = (0..triangles)
            .map(|_| std::array::from_fn(|_| tokens.next().unwrap().parse().unwrap()))
            .collect();
        meshes.push((points, indices));
    }
    assert_eq!(tokens.next(), Some("SHOTS"));
    let cases: usize = tokens.next().unwrap().parse().unwrap();
    let frames = TargetFrames::new(vec![]);
    let mut fired = 0;
    for _ in 0..cases {
        assert_eq!(tokens.next(), Some("S"));
        let label = tokens.next().unwrap();
        let origin = vector(&mut tokens);
        let quaternion = [
            number(&mut tokens),
            number(&mut tokens),
            number(&mut tokens),
            number(&mut tokens),
        ];
        let direction = vector(&mut tokens);
        let entry_m = number(&mut tokens);
        for (caliber, speeds) in [(Caliber::Mm17, [25., 40.]), (Caliber::Mm42, [12., 24.])] {
            for speed in speeds {
                let mut world = WorldPhysics::new(&[], -100.);
                for (vertices, triangles) in &meshes {
                    world
                        .add_static_mesh(vertices.clone(), triangles.clone())
                        .unwrap();
                }
                let mut control = WorldPhysics::new(&[], -100.);
                let pose = Pose {
                    translation_m: origin,
                    rotation_wxyz: quaternion,
                };
                let shot = Shot {
                    caliber,
                    speed_m_s: speed,
                };
                world.fire(0, pose, shot, None).unwrap();
                control.fire(0, pose, shot, None).unwrap();
                let mut responded = false;
                for tick in 0..16 {
                    world.step(tick * tick_ns(), &frames).unwrap();
                    control.step(tick * tick_ns(), &frames).unwrap();
                    let balls = world.snapshot();
                    let free = control.snapshot();
                    let ball = balls
                        .first()
                        .expect("shot unexpectedly disappeared before contact");
                    let free = free.first().unwrap();
                    let difference: f64 = ball
                        .velocity_m_s
                        .into_iter()
                        .zip(free.velocity_m_s)
                        .map(|(a, b)| (a - b).powi(2))
                        .sum();
                    if ball.first_contact_ns.is_some() || difference > 1e-8 {
                        responded = true;
                        break;
                    }
                    let progress = dot(
                        std::array::from_fn(|i| ball.position_m[i] - origin[i]),
                        direction,
                    );
                    assert!(
                        progress <= entry_m + caliber.diameter_m(),
                        "passed profile mesh without collision: {label}, {caliber:?}, speed={speed}, progress={progress}"
                    );
                }
                assert!(
                    responded,
                    "no collision response: {label}, {caliber:?}, speed={speed}"
                );
                fired += 1;
            }
        }
    }
    assert!(tokens.next().is_none());
    println!(
        "Dart mesh CCD: {count} meshes, {cases} trajectories, {fired} shots passed at 128 Hz (16.8/42.5 mm; 12/24/25/40 m/s)"
    );
}
